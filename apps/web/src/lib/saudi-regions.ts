export const REGION_NAMES = Object.keys(SAUDI_REGIONS);
export const citiesOf = (region?: string | null): string[] => (region && SAUDI_REGIONS[region]) || [];
// إيجاد منطقة مدينة معيّنة (لو عُرفت المدينة فقط)
export function regionOfCity(city?: string | null): string | undefined {
  if (!city) return undefined;
  for (const [region, cities] of Object.entries(SAUDI_REGIONS)) if (cities.includes(city)) return region;
  return undefined;
}
